function clockwise(footprint) {
  const area = footprint.slice(1).reduce((sum, [x, y], i) => {
    const [previousX, previousY] = footprint[i];
    return sum + previousX * y - x * previousY;
  }, 0);
  return area > 0 ? footprint.toReversed() : footprint;
}

